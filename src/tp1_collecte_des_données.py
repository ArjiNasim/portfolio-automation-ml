# FONCTION 1 : Scraping des ratios financiers
# ─────────────────────────────────────────────────────────────

def scrape_financial_ratios(companies: dict = companies,
                             ratio_keys: list = ratios.keys(),
                             output_file: str = "financial_ratios.csv") -> pd.DataFrame:
    """
    Récupère les ratios fondamentaux de chaque entreprise via Yahoo Finance
    et exporte le résultat dans `output_file` (CSV).

    return :
    ---> pd.DataFrame  (index = nom entreprise, colonnes = ratios)
    """
    print("\n[TP1] Scraping des ratios financiers...")

    records = []

    for company_name, symbol in companies.items():
        print(f"  → {company_name} ({symbol})", end=" ")
        row = {"Company": company_name}
        try:
            info = yf.Ticker(symbol).info
            for key in ratio_keys:
                row[key] = info.get(key, None)
            print("✓")
        except Exception as e:
            for key in ratio_keys:
                row[key] = None
            print(f"⚠ {e}")

        records.append(row)
        time.sleep(0.3)   # pause pour recuperer les données de Yahoo Finance

    df = pd.DataFrame(records).set_index("Company")
    df.to_csv(output_file)

    print(f"\n  ✅ Ratios exportés → '{output_file}'")
    return df

