# Pour récuperer la date d'hier
def get_date_range(years: int = 5):
    """
    ---------------
    Les APIs financières (Yahoo Finance) ne fournissent le cours de clôture
    d'une journée qu'après la fermeture du marché. Si on exécute le pipeline
    en cours de journée, aujourd'hui n'est pas encore disponible.
    On prend donc J-1 comme dernière date disponible.
    """
    end_date   = datetime.today() - timedelta(days=1)
    start_date = end_date - timedelta(days=years * 365)

    return start_date.strftime("%Y-%m-%d"), end_date.strftime("%Y-%m-%d")


