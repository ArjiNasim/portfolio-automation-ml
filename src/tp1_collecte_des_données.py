# FONCTION 2 : Scraping de l'historique des cours
# ─────────────────────────────────────────────────────────────

def scrape_historical_prices(companies: dict = companies,
                             output_dir: str = "Companies_historical_data", years: int = 5):
    start_date, end_date = get_date_range(years)
    os.makedirs(output_dir, exist_ok=True)
    results = {}

    for company_name, symbol in companies.items():
        print(f"  → {company_name} ({symbol})", end=" ", flush=True)
        try:
            # Ajout de auto_adjust pour éviter les warnings et avoir des données propres
            raw = yf.download(symbol, start=start_date, end=end_date, progress=False, auto_adjust=True)

            if raw.empty:
                print("⚠ Vide")
                continue

            # Gestion robuste des colonnes (yfinance v0.2.40+)
            if isinstance(raw.columns, pd.MultiIndex):
                df = raw['Close'][[symbol]].copy() # On sélectionne spécifiquement le ticker
                df.columns = ['Close']
            else:
                df = raw[['Close']].copy()

            # ─── MODIFICATION CONSIGNES TP 1 ───
            # 1. Récupérer les données 'Close' de chaque jour [cite: 177] (Fait ci-dessus)

            # 2. Créer une colonne 'Next Day Close' avec la commande shift
            # On utilise shift(-1) pour amener le prix de clôture du lendemain (J+1) sur la ligne d'aujourd'hui
            df['Next Day Close'] = df['Close'].shift(-1)

            # 3. Créer une colonne 'Rendement' qui calcule les variations de stocks d'un jour à l'autre
            df["Rendement"] = (df["Next Day Close"] - df["Close"]) / df["Close"]

            # On enlève la dernière ligne qui contient un NaN (car il n'y a pas de lendemain disponible pour elle)
            df = df.dropna()
            # ────────────────────────────────────

            # Nettoyage nom de fichier plus élégant
            safe_name = "".join([c for c in company_name if c.isalnum() or c in (" ", "_")]).replace(" ", "_")
            filepath = os.path.join(output_dir, f"{safe_name}.csv") # [cite: 180]
            df.to_csv(filepath)

            results[company_name] = df
            print(f"✓ ({len(df)} jours)")

        except Exception as e:
            print(f"⚠ Erreur : {e}")

        time.sleep(0.3)

    return results

