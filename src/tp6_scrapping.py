def run_tp6(companies_dict, api_key):
    """
    Fonction principale à appeler depuis le main.py
    companies_dict : Dictionnaire au format {"Nom": "Ticker"} issu du TP1
    """
    print("\n" + "="*50 + "\n LANCEMENT DU TP6 - SCRAPPING NEWS\n" + "="*50)

    if not api_key or api_key == "VOTRE_CLE_API_ICI":
        print("❌ ERREUR: Clé API manquante. Allez sur newsapi.org pour en générer une.")
        return {}

    all_news = {}

    for i, (company, ticker) in enumerate(companies_dict.items()):
        all_news[company] = get_news_by_date(company, ticker, api_key)

        # Pause pour éviter de se faire bloquer par l'API (Rate limiting)
        time.sleep(1)
        if (i + 1) % 20 == 0:
            print("⏸️ Pause de sécurité (30 secondes) pour éviter le blocage API...")
            time.sleep(30)

    print("\n✅ Scrapping terminé. Tous les fichiers JSON sont dans le dossier local 'companies_news/'.")

    # Résumé rapide
    print("\n--- Bilan des articles en mémoire ---")
    for company, news in all_news.items():
        total = sum(len(articles) for articles in news.values())
        print(f" - {company} : {total} articles")

    return all_news


