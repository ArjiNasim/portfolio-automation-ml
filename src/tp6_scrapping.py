# ── Constantes et Configuration ────────────────────────────
NEWS_FOLDER = "companies_news"
os.makedirs(NEWS_FOLDER, exist_ok=True)

# Groupes géographiques
ASIAN_SUFFIXES    = [".KS", ".T", "TCEHY", "BABA", "BIDU", "JD", "BYDDY", "1398.HK", "NTDOY", "HYMLF", "RELIANCE.NS", "TCS.NS"]
EUROPEAN_SUFFIXES = [".PA", ".L", ".DE", ".AS"]

SOURCES_US     = "financial-post,the-wall-street-journal,bloomberg,the-washington-post,reuters,the-economist,business-insider,fortune,forbes,cnbc,the-verge,techcrunch,wired,ars-technica,engadget,bbc-news,the-guardian-uk,independent,al-jazeera-english,associated-press"
SOURCES_EUROPE = "bbc-news,the-guardian-uk,independent,reuters,the-economist,financial-post,bloomberg,al-jazeera-english,associated-press,business-insider,fortune,forbes,cnbc,le-monde,handelsblatt,der-spiegel,ansa,rtl-nieuws,les-echos,el-mundo"
SOURCES_ASIA   = "reuters,bloomberg,bbc-news,al-jazeera-english,associated-press,the-economist,cnbc,fortune,business-insider,financial-post,the-japan-times,the-straits-times,south-china-morning-post,nikkei,hindustan-times,the-times-of-india,the-hindu,asia-times,channel-news-asia,the-diplomat"

SEARCH_NAMES = {
    "Louis Vuitton (LVMH)": "LVMH",
    "JP Morgan": "JPMorgan",
    "Johnson & Johnson": "Johnson Johnson",
    "Tata Consultancy Services": "TCS",
    "Reliance Industries": "Reliance",
    "JD.com": "JD.com",
}


# =====================================================================
#  FONCTIONS UTILITAIRES
# =====================================================================

def _get_geographic_sources(ticker):
    """ Retourne la liste des sources adaptée à la géographie du ticker. """
    if any(s in ticker for s in ASIAN_SUFFIXES):
        return SOURCES_ASIA
    elif any(ticker.endswith(s) for s in EUROPEAN_SUFFIXES):
        return SOURCES_EUROPE
    return SOURCES_US


def _get_search_name(company):
    """ Adapte le nom de l'entreprise pour optimiser la recherche de news. """
    return SEARCH_NAMES.get(company, company)


def load_existing_news(company_name):
    """ Charge le fichier JSON existant s'il y en a un pour éviter les doublons. """
    file_path = os.path.join(NEWS_FOLDER, f"{company_name.replace(' ', '_')}.json")
    if os.path.exists(file_path):
        with open(file_path, "r", encoding='utf-8') as f:
            return json.load(f)
    return {}


# =====================================================================
#  CŒUR DU PIPELINE
# =====================================================================

def get_news_by_date(company_name, ticker, api_key, days_back=10):
    """ Scrape les articles pertinents sur NewsAPI et les sauvegarde. """
    url = 'https://newsapi.org/v2/everything'
    last_day  = datetime.today().strftime('%Y-%m-%d')
    first_day = (datetime.today() - timedelta(days=days_back)).strftime('%Y-%m-%d')
    search_query = _get_search_name(company_name)

    params = {
        "sources": _get_geographic_sources(ticker),
        "q": search_query,
        "apiKey": api_key,
        "language": "en",
        "pageSize": 100,
        "from": first_day,
        "to": last_day,
        "sortBy": "relevancy",
    }

    news_dict = load_existing_news(company_name)

    try:
        response = requests.get(url, params=params)
    except Exception as e:
        print(f"❌ Erreur de connexion pour {company_name} : {e}")
        return news_dict

    if response.status_code != 200:
        message = response.json().get('message', 'Erreur inconnue')
        print(f"❌ Erreur API {response.status_code} pour {company_name} : {message}")
        return news_dict

    articles  = response.json().get("articles", [])
    new_count = 0

    for article in articles:
        title       = article.get("title", "") or ""
        description = article.get("description", "") or ""
        source      = article.get("source", {}).get("name", "")
        published   = article.get("publishedAt", "")

        # Filtre strict : le nom de l'entreprise doit être dans le titre ou la description
        if search_query.lower() not in title.lower() and search_query.lower() not in description.lower():
            continue

        if not published:
            continue

        date = published.split("T")[0]
        if date not in news_dict:
            news_dict[date] = []

        existing_titles = [a["title"] for a in news_dict[date]]
        if title not in existing_titles:
            news_dict[date].append({
                "title": title,
                "description": description,
                "source": source,
                "publishedAt": published,
            })
            new_count += 1

    file_path = os.path.join(NEWS_FOLDER, f"{company_name.replace(' ', '_')}.json")
    with open(file_path, "w", encoding='utf-8') as f:
        json.dump(news_dict, f, indent=4, ensure_ascii=False)

    print(f"✅ {company_name} — {new_count} nouveaux articles ajoutés → {file_path}")
    return news_dict


