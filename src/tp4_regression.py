#  POINT D'ENTRÉE PRINCIPAL
# =====================================================================

def run_tp4(companies_to_process=None):
    print("\n" + "="*60 + "\n LANCEMENT DU TP4 - RÉGRESSION & FORECASTING\n" + "="*60)

    csv_files = glob.glob(os.path.join(HISTORICAL_DIR, "*.csv"))
    if not csv_files:
        print(f"❌ Aucun historique CSV trouvé dans '{HISTORICAL_DIR}'.")
        return

    print(f"🔍 {len(csv_files)} fichiers d'entreprises détectés.")

    for file_path in csv_files:
        filename = os.path.basename(file_path).replace(".csv", "")

        # MODIFICATION : Si companies_to_process est fourni, on filtre. Sinon, on prend TOUT.
        if companies_to_process is not None and filename not in companies_to_process:
            continue

        company_name = filename.replace("_history", "").replace("_", " ")
        print(f"\n Processing : {company_name}...")

        try:
            # 1. Préparation des données
            X_train, X_test, y_train, y_test, scaler, y_raw = prepare_regression_data(file_path, n_days=30)

            # 2. Pipeline d'entraînement et d'évaluation
            df_perf, models = run_regression_pipeline(X_train, X_test, y_train, y_test, scaler, y_raw, company_name)
            print(f" ├─ Synthèse des erreurs sur Test Set :")
            print(df_perf.sort_values(by="RMSE").to_string())

            # 3. Projection 10 jours dans le futur
            last_window = X_train[-1][:30]
            last_feats  = X_train[-1][30:]
            df_forecast = plot_multistep_forecast(y_raw, models, last_window, last_feats, scaler, n_future=10, company_name=company_name)

            print(f" ├─ Synthèse Projection Future (10 jours) :")
            print(df_forecast.sort_values(by="RMSE (10j)").to_string())
            print(f"✅ Terminé pour {company_name}. Graphiques sauvegardés dans '{PLOTS_DIR}'.")

        except Exception as e:
            print(f"❌ Erreur sur {company_name} : {e}")


if __name__ == "__main__":
    # En laissant les parenthèses vides, le script va scanner et exécuter TOUTES les entreprises !
    run_tp4()
