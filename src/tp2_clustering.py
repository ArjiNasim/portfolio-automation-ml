def elbow_method(data: np.ndarray, k_max: int = 10, title: str = "Elbow Method"):
    """
    Trace la courbe inertie vs K pour identifier le coude optimal.
    Part de K=1 (référence) jusqu'à k_max.
    """
    inertias = []
    k_range  = range(1, k_max + 1)

    for k in k_range:
        km = KMeans(n_clusters=k, random_state=42, n_init=10)
        km.fit(data)
        inertias.append(km.inertia_)

    # ── Détection automatique du coude ──
    coords = np.column_stack([np.arange(len(inertias)), inertias])
    line   = coords[-1] - coords[0]
    line  /= np.linalg.norm(line)
    dists  = np.abs(np.cross(line, coords[0] - coords))
    best_k = int(np.argmax(dists)) + 1  # +1 car range commence à 1

    fig, ax = plt.subplots(figsize=(9, 5))
    ax.plot(k_range, inertias, "o-", color="#4FC3F7",
            linewidth=2.5, markersize=7, markerfacecolor="white",
            markeredgewidth=2)
    ax.axvline(best_k, color="#FFB74D", linestyle="--",
               linewidth=1.8, label=f"Coude suggéré : K={best_k}")
    ax.set_xlabel("Nombre de clusters K")
    ax.set_ylabel("Inertie intra-cluster")
    ax.set_title(title)
    ax.legend()
    ax.grid(True)
    plt.tight_layout()
    plt.savefig(os.path.join(PLOTS_DIR, f"elbow_{title.replace(' ','_')}.png"),
                dpi=150, bbox_inches="tight")
    plt.show()

    print(f"  [Elbow] Coude détecté automatiquement à K={best_k}")
    return inertias


def do_kmeans_clustering(data, df_clean, n_clusters, label="financial"):
    km     = KMeans(n_clusters=n_clusters, random_state=42, n_init=10)
    labels = km.fit_predict(data)

    df_result = df_clean.copy()
    df_result["Cluster"] = labels

    print(f"\n  Profil moyen par cluster ({label}) :")
    print(df_result.groupby("Cluster").mean().round(3).to_string())

    # ── t-SNE ──────────────────────────────────────────────
    perplexity = min(30, len(data) - 1)
    coords = TSNE(n_components=2, perplexity=perplexity,
                  random_state=42, init="pca",
                  learning_rate="auto").fit_transform(data)

    colors = [CLUSTER_COLORS[i % len(CLUSTER_COLORS)] for i in range(n_clusters)]

    fig, ax = plt.subplots(figsize=(12, 8))

    for k in range(n_clusters):
        mask = labels == k
        ax.scatter(coords[mask, 0], coords[mask, 1],
                   color=colors[k], s=90, alpha=0.9,
                   edgecolors="white", linewidths=0.4,
                   label=f"Cluster {k} ({mask.sum()} entreprises)")

    for i, name in enumerate(df_clean.index):
        ax.annotate(name,
                    xy=(coords[i, 0], coords[i, 1]),
                    xytext=(6, 4), textcoords="offset points",
                    fontsize=7, alpha=0.85, color="#d0d0d0")

    ax.legend(title="Clusters", loc="best", framealpha=0.8)
    ax.set_title(f"K-Means ({n_clusters} clusters) — {label} — t-SNE")
    ax.set_xlabel("t-SNE dim 1")
    ax.set_ylabel("t-SNE dim 2")
    plt.tight_layout()
    plt.savefig(os.path.join(PLOTS_DIR, f"kmeans_tsne_{label}.png"),
                dpi=150, bbox_inches="tight")
    plt.show()

    return df_result, labels


