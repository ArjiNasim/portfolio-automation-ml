def cluster_by_correlation(returns_df, n_clusters=5):
    """
    ⚠️  POINT CLÉ : on convertit la matrice de corrélation en matrice de
    DISTANCES (dist = 1 - corr) avant d'appliquer linkage/Ward.
    Linkage attend des distances, pas des similarités.
    """
    corr_matrix = returns_df.corr()

    # Conversion correcte corrélation → distance
    dist_matrix = np.clip(1 - corr_matrix.values, 0, None)
    linked      = linkage(squareform(dist_matrix), method="ward")

    # ── Dendrogramme avec ligne de coupe ───────────────────
    distances = linked[:, 2]
    threshold = (distances[-n_clusters] + distances[-n_clusters + 1]) / 2

    fig, ax = plt.subplots(figsize=(18, 7))
    dendrogram(linked,
               labels=list(corr_matrix.index),
               leaf_rotation=90, leaf_font_size=7,
               color_threshold=threshold,
               ax=ax)
    ax.axhline(y=threshold, color="#FFB74D", linestyle="--",
               linewidth=1.8, label=f"Coupe → K={n_clusters} clusters")
    ax.set_title("Dendrogramme — Clustering par corrélations de rendements")
    ax.set_xlabel("Entreprises")
    ax.set_ylabel("Distance (1 − corrélation, Ward)")
    ax.legend()
    plt.tight_layout()
    plt.savefig(os.path.join(PLOTS_DIR, "dendrogram_returns.png"),
                dpi=150, bbox_inches="tight")
    plt.show()

    # ── Heatmap de corrélation triée par cluster ────────────
    cluster_labels = fcluster(linked, t=n_clusters, criterion="maxclust")
    order = np.argsort(cluster_labels)
    corr_sorted = corr_matrix.iloc[order, order]

    fig, ax = plt.subplots(figsize=(16, 13))
    sns.heatmap(corr_sorted,
                cmap="RdYlGn", vmin=-1, vmax=1,
                xticklabels=corr_sorted.columns,
                yticklabels=corr_sorted.columns,
                linewidths=0, ax=ax,
                cbar_kws={"label": "Corrélation"})
    ax.set_xticklabels(ax.get_xticklabels(), rotation=90, fontsize=6)
    ax.set_yticklabels(ax.get_yticklabels(), rotation=0, fontsize=6)
    ax.set_title("Matrice de corrélation des rendements (triée par cluster)")
    plt.tight_layout()
    plt.savefig(os.path.join(PLOTS_DIR, "heatmap_correlation.png"),
                dpi=150, bbox_inches="tight")
    plt.show()

    df_result = pd.DataFrame({
        "Company": corr_matrix.index,
        "Cluster": cluster_labels
    }).set_index("Company")

    return df_result, corr_matrix


