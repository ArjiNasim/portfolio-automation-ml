def plot_dendrogram(data, df_clean, k_suggestion=4, label="risk"):
    """
    Trace le dendrogramme avec :
    - une ligne de coupe visuelle (comme Code 2, très pédagogique)
    - coloration automatique des branches (comme Code 1)
    """
    linked    = linkage(data, method="ward")
    distances = linked[:, 2]

    # Seuil de coupe entre les deux derniers sauts de distance
    threshold = (distances[-k_suggestion] + distances[-k_suggestion + 1]) / 2

    fig, ax = plt.subplots(figsize=(16, 7))
    dendrogram(linked,
               labels=list(df_clean.index),
               leaf_rotation=90,
               leaf_font_size=8,
               color_threshold=threshold,
               ax=ax)

    ax.axhline(y=threshold, color="#FFB74D", linestyle="--",
               linewidth=1.8, label=f"Coupe → K={k_suggestion} clusters")
    ax.set_title(f"Dendrogramme — Clustering hiérarchique ({label})")
    ax.set_xlabel("Entreprises")
    ax.set_ylabel("Distance (Ward)")
    ax.legend()
    plt.tight_layout()
    plt.savefig(os.path.join(PLOTS_DIR, f"dendrogram_{label}.png"),
                dpi=150, bbox_inches="tight")
    plt.show()

    return linked


