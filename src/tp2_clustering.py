def _auto_eps(data: np.ndarray, k: int = 4) -> float:
    """
    Calibre eps via la méthode k-distance.

    Pour chaque point, on calcule la distance à son k-ème voisin.
    Le "coude" de la courbe triée représente la frontière naturelle
    entre zones denses (clusters) et zones creuses (bruit).
    """
    k       = min(k, len(data) - 1)
    nbrs    = NearestNeighbors(n_neighbors=k).fit(data)
    dists, _= nbrs.kneighbors(data)
    kdists  = np.sort(dists[:, -1])

    n      = len(kdists)
    coords = np.column_stack([np.arange(n), kdists])
    line   = coords[-1] - coords[0]
    line  /= np.linalg.norm(line)
    dists_to_line = np.abs(np.cross(line, coords[0] - coords))
    elbow_idx     = np.argmax(dists_to_line)
    eps_auto      = float(kdists[elbow_idx])

    print(f"    [eps auto] {eps_auto:.4f} (coude idx {elbow_idx}/{n})")
    return eps_auto


