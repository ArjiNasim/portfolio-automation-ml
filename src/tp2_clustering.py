def _silhouette_safe(data, labels, noise_threshold=0.5):
    """
    Calcule le silhouette score DBSCAN de façon honnête.

    Règle anti-biais : si plus de `noise_threshold` (défaut 50%) des points
    sont marqués bruit (-1), on retourne N/A.

    Pourquoi ? Avec 37/41 outliers, le score est calculé sur 4 points
    formant un micro-cluster parfait → score artificiellement élevé
    qui ne reflète pas la qualité réelle du clustering.
    """
    n_noise     = (labels == -1).sum()
    noise_ratio = n_noise / len(labels)

    if noise_ratio > noise_threshold:
        print(f"  ⚠️  Silhouette N/A : {n_noise}/{len(labels)} points "
              f"({noise_ratio:.0%}) en bruit → score biaisé, ignoré.")
        return np.nan

    mask = labels != -1
    if len(set(labels[mask])) < 2:
        return np.nan

    return round(silhouette_score(data[mask], labels[mask]), 4)


def _dbscan_with_fallback(data, label="", noise_threshold=0.5):
    """
    Cherche les paramètres DBSCAN maximisant le silhouette score
    sous contrainte : taux de bruit ≤ noise_threshold.

    On explore une grille (factor × eps_auto, min_samples).
    Cela évite de retenir une solution qui "triche" en mettant
    presque tout le monde en bruit pour scorer haut sur 3 points.
    """
    base_eps   = _auto_eps(data, k=min(4, len(data) - 1))
    best_score = -2.0
    best_labels, best_params = None, None

    for factor in [1.0, 0.9, 0.75, 0.6, 0.5, 0.4, 0.3]:
        for ms in [3, 2]:
            eps_try     = base_eps * factor
            lbl         = DBSCAN(eps=eps_try, min_samples=ms).fit_predict(data)
            noise_ratio = (lbl == -1).sum() / len(lbl)
            mask        = lbl != -1

            # On rejette les solutions avec trop de bruit
            if noise_ratio > noise_threshold:
                continue
            if len(set(lbl[mask])) < 2:
                continue

            score = silhouette_score(data[mask], lbl[mask])
            if score > best_score:
                best_score  = score
                best_labels = lbl
                best_params = (eps_try, ms)

    if best_labels is None:
        print(f"  [DBSCAN {label}] ⚠️  Aucun paramètre valide avec ≤{noise_threshold:.0%} bruit.")
        best_labels = np.full(len(data), -1)
        best_params = (base_eps, 3)
    else:
        n_noise = (best_labels == -1).sum()
        print(f"  [DBSCAN {label}] ✅ eps={best_params[0]:.4f}, "
              f"min_samples={best_params[1]} | silhouette={best_score:.4f} | "
              f"bruit={n_noise}/{len(data)} ({n_noise/len(data):.0%})")

    return best_labels, best_params


def evaluate_all_algorithms(X_fin, X_risk, returns_df, corr_matrix,
                            n_clusters_financial=4,
                            n_clusters_risk=4,
                            n_clusters_returns=5,
                            noise_threshold=0.5):
    """
    Compare K-Means, Hierarchical et DBSCAN sur les 3 datasets.

    Anti-biais DBSCAN : on rejette tout paramétrage où >50% des points
    sont en bruit (-1), car le silhouette score serait calculé sur un
    sous-ensemble trop petit et donnerait un score artificiellement élevé.
    """
    print("\n[TP2] Évaluation comparative...\n")

    X_ret = StandardScaler().fit_transform(returns_df.T.values)
    df_ret_dummy = pd.DataFrame(index=returns_df.columns)

    _, df_fin_clean, _ = preprocess_for_financial_clustering()
    _, df_risk_clean, _= preprocess_for_risk_clustering()

    datasets = {
        "Financial": (X_fin,  n_clusters_financial, df_fin_clean),
        "Risk":      (X_risk, n_clusters_risk,       df_risk_clean),
        "Returns":   (X_ret,  n_clusters_returns,    df_ret_dummy),
    }

    results     = {}
    dbscan_runs = {}

    for ds, (X, k, df_clean) in datasets.items():
        km_labels   = KMeans(k, random_state=42, n_init=10).fit_predict(X)
        hier_labels = AgglomerativeClustering(k, linkage="ward").fit_predict(X)
        db_labels, db_params = _dbscan_with_fallback(
            X, label=ds, noise_threshold=noise_threshold
        )
        dbscan_runs[ds] = (X, df_clean, db_labels, db_params)

        results[ds] = {
            "K-Means":      _silhouette_safe(X, km_labels),
            "Hierarchical": _silhouette_safe(X, hier_labels),
            "DBSCAN":       _silhouette_safe(X, db_labels,
                                             noise_threshold=noise_threshold),
        }

    # ── t-SNE pour les 3 datasets DBSCAN ───────────────────
    print("\n  [DBSCAN] Visualisations t-SNE des 3 datasets...\n")
    for ds, (X, df_clean, db_labels, (eps, ms)) in dbscan_runs.items():
        _plot_dbscan_tsne(X, df_clean, db_labels, eps, ms, label=ds)

    df_scores = pd.DataFrame(results).T
    df_scores.index.name = "Dataset"

    # ── Tableau avec fond blanc ─────────────────────────────
    df_display = df_scores.copy().astype(object)
    df_display = df_display.where(df_scores.notna(), other="N/A")

    fig, ax = plt.subplots(figsize=(8, 3.5))
    ax.axis("off")
    fig.patch.set_facecolor("white")

    cell_colors = []
    for row in df_scores.itertuples(index=False):
        row_colors = []
        values = [v for v in row if isinstance(v, float) and not np.isnan(v)]
        best   = max(values) if values else None
        for v in row:
            if isinstance(v, float) and not np.isnan(v) and v == best:
                row_colors.append("#c8e6c9")   # vert clair = meilleur
            elif not isinstance(v, float) or np.isnan(v):
                row_colors.append("#ffcdd2")   # rouge clair = N/A
            else:
                row_colors.append("#ffffff")   # blanc = valeur normale
        cell_colors.append(row_colors)

    tbl = ax.table(
        cellText=df_display.values.tolist(),
        rowLabels=df_scores.index,
        colLabels=df_scores.columns,
        cellLoc="center", loc="center",
        cellColours=cell_colors,
    )
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(11)
    tbl.scale(1.4, 2.0)

    for (r, c), cell in tbl.get_celld().items():
        cell.set_edgecolor("#cccccc")
        if r == 0 or c == -1:
            cell.set_facecolor("#1565c0")
            cell.set_text_props(color="white", fontweight="bold")
        else:
            cell.set_text_props(color="#212121")

    ax.set_title("Silhouette Scores — Comparaison des algorithmes\n"
                 "(vert = meilleur score par ligne, rouge = N/A)",
                 pad=15, color="#212121", fontsize=12)
    plt.tight_layout()
    plt.savefig(os.path.join(PLOTS_DIR, "silhouette_scores_table.png"),
                dpi=150, bbox_inches="tight")
    plt.show()

    print("\n  ── Silhouette Scores ──")
    print(df_display.to_string())
    df_scores.to_csv("silhouette_scores.csv")
    return df_scores


