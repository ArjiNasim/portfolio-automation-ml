def do_dbscan_clustering(data, df_clean, eps=None, min_samples=3, label="", plot=True):
    """
    DBSCAN avec calibration automatique d'eps (méthode k-distance).
    """
    if eps is None:
        eps = _auto_eps(data, k=min(4, len(data) - 1)) * 0.7

    labels = DBSCAN(eps=eps, min_samples=min_samples).fit_predict(data)

    df_result = df_clean.copy()
    df_result["Cluster"] = labels

    n_clusters = len(set(labels)) - (1 if -1 in labels else 0)
    n_noise    = list(labels).count(-1)

    print(f"\n  [DBSCAN {label}] eps={eps:.4f}, min_samples={min_samples}")
    print(f"  → {n_clusters} clusters | {n_noise} points bruit")

    if n_clusters > 0:
        cc = (df_result[df_result["Cluster"] != -1]["Cluster"]
              .value_counts().sort_index())
        for c_id, count in cc.items():
            print(f"     Cluster {c_id} : {count} entreprises")

    return df_result, labels


