def _robust_preprocess(df_sel: pd.DataFrame, label: str):
    """
    Stratégie de nettoyage en 3 étapes :

    Étape 1 — Supprimer les COLONNES avec > 50 % de NA
        Yahoo Finance ne retourne pas certains ratios pour les entreprises
        non-américaines. Si une colonne est vide à 50 %+, elle n'apporte
        pas d'information fiable.

    Étape 2 — Supprimer les LIGNES avec > 50 % de NA restants
        Élimine les entreprises vraiment trop incomplètes.

    Étape 3 — Imputer les NA restants par la MÉDIANE
        On préfère la médiane à la moyenne : les ratios financiers ont des
        distributions très asymétriques (ex. PE de Tesla) qui biaisent
        la moyenne mais pas la médiane.
    """
    n_total = len(df_sel)

    thresh_col   = int(n_total * 0.5)
    df           = df_sel.dropna(axis=1, thresh=thresh_col)
    dropped_cols = set(df_sel.columns) - set(df.columns)
    if dropped_cols:
        print(f"  [{label}] Colonnes retirées (>50% NA) : {dropped_cols}")

    thresh_row = int(df.shape[1] * 0.5)
    df         = df.dropna(axis=0, thresh=thresh_row)
    print(f"  [{label}] {n_total - len(df)} entreprises retirées (>50% NA) "
          f"→ {len(df)} conservées.")

    n_na = df.isnull().sum().sum()
    if n_na > 0:
        df = df.fillna(df.median())
        print(f"  [{label}] {n_na} NA imputés par la médiane.")

    scaler   = StandardScaler()
    X_scaled = scaler.fit_transform(df)
    return X_scaled, df, scaler


