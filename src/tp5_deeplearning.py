def build_mlp_model(input_dim, hidden_dims, dropout_rate, activation, optimizer):
    model = tf.keras.Sequential()
    model.add(tf.keras.layers.Dense(hidden_dims[0], activation=activation, input_shape=(input_dim,)))
    model.add(tf.keras.layers.Dropout(dropout_rate))
    for dim in hidden_dims[1:]:
        model.add(tf.keras.layers.Dense(dim, activation=activation))
        model.add(tf.keras.layers.Dropout(dropout_rate))
    model.add(tf.keras.layers.Dense(1))
    model.compile(optimizer=optimizer, loss='mse')
    return model

def build_rnn_model(input_shape, hidden_dims, dropout_rate, activation, optimizer):
    model = tf.keras.Sequential()
    model.add(tf.keras.layers.SimpleRNN(hidden_dims[0], activation=activation,
                                        return_sequences=len(hidden_dims)>1, input_shape=input_shape))
    model.add(tf.keras.layers.Dropout(dropout_rate))
    for i, dim in enumerate(hidden_dims[1:]):
        model.add(tf.keras.layers.SimpleRNN(dim, activation=activation, return_sequences=i < len(hidden_dims)-2))
        model.add(tf.keras.layers.Dropout(dropout_rate))
    model.add(tf.keras.layers.Dense(1))
    model.compile(optimizer=optimizer, loss='mse')
    return model

def build_lstm_model(input_shape, hidden_dims, dropout_rate, activation, optimizer):
    model = tf.keras.Sequential()
    model.add(tf.keras.layers.LSTM(hidden_dims[0], activation=activation,
                                   return_sequences=len(hidden_dims)>1, input_shape=input_shape))
    model.add(tf.keras.layers.Dropout(dropout_rate))
    for i, dim in enumerate(hidden_dims[1:]):
        model.add(tf.keras.layers.LSTM(dim, activation=activation, return_sequences=i < len(hidden_dims)-2))
        model.add(tf.keras.layers.Dropout(dropout_rate))
    model.add(tf.keras.layers.Dense(1))
    model.compile(optimizer=optimizer, loss='mse')
    return model

def build_hybrid_model(input_shape, lstm_units, dense_units, dropout_rate, optimizer):
    model = tf.keras.Sequential()
    model.add(tf.keras.layers.LSTM(lstm_units, activation='tanh', input_shape=input_shape, return_sequences=False))
    model.add(tf.keras.layers.Dropout(dropout_rate))
    for units in dense_units:
        model.add(tf.keras.layers.Dense(units, activation='relu'))
        model.add(tf.keras.layers.Dropout(dropout_rate))
    model.add(tf.keras.layers.Dense(1))
    model.compile(optimizer=optimizer, loss='mse')
    return model


# =====================================================================
#  3. ENTRAÎNEMENT ET OPTIMISATION (GRID SEARCH DL)
# =====================================================================

def run_dl_pipeline(X_tr_2d, X_te_2d, X_tr_3d, X_te_3d, y_tr, y_te, scaler_close, y_raw, input_dim):
    """ Recherche les meilleurs hyperparamètres pour chaque architecture DL. """
    best_models = {}

    # Grille réduite pour un temps d'exécution raisonnable
    dl_configs = [
        {"hidden_dims": [64, 32], "lr": 0.001, "drop": 0.0},
        {"hidden_dims": [128, 64], "lr": 0.001, "drop": 0.2}
    ]

    for model_type in ["MLP", "RNN", "LSTM"]:
        best_rmse = float('inf')
        best_cfg  = None

        X_tr = X_tr_2d if model_type == "MLP" else X_tr_3d
        X_te = X_te_2d if model_type == "MLP" else X_te_3d
        in_shape = input_dim if model_type == "MLP" else (input_dim, 1)

        for cfg in dl_configs:
            opt = tf.keras.optimizers.Adam(learning_rate=cfg["lr"])
            act = "tanh" if model_type in ["RNN", "LSTM"] else "relu"

            if model_type == "MLP":
                m = build_mlp_model(in_shape, cfg["hidden_dims"], cfg["drop"], act, opt)
            elif model_type == "RNN":
                m = build_rnn_model(in_shape, cfg["hidden_dims"], cfg["drop"], act, opt)
            else:
                m = build_lstm_model(in_shape, cfg["hidden_dims"], cfg["drop"], act, opt)

            # Entraînement silencieux
            m.fit(X_tr, y_tr, epochs=15, batch_size=32, verbose=0)

            preds = scaler_close.inverse_transform(m.predict(X_te, verbose=0).reshape(-1, 1)).flatten()
            rmse  = np.sqrt(mean_squared_error(y_raw, preds))

            if rmse < best_rmse:
                best_rmse = rmse
                best_cfg = {
                    "model": m, "name": f"{model_type} {cfg['hidden_dims']}",
                    "preds": preds,
                    "metrics": {"MSE": round(mean_squared_error(y_raw, preds),4),
                                "RMSE": round(rmse,4),
                                "MAE": round(mean_absolute_error(y_raw, preds),4)}
                }
        best_models[model_type] = best_cfg

    # Modèle Hybride
    best_hybrid_rmse = float('inf')
    for lstm_u, dense_u in [(64, [32]), (128, [64, 32])]:
        opt = tf.keras.optimizers.Adam(learning_rate=0.001)
        m = build_hybrid_model((input_dim, 1), lstm_u, dense_u, 0.2, opt)
        m.fit(X_tr_3d, y_tr, epochs=15, batch_size=32, verbose=0)

        preds = scaler_close.inverse_transform(m.predict(X_te_3d, verbose=0).reshape(-1, 1)).flatten()
        rmse  = np.sqrt(mean_squared_error(y_raw, preds))

        if rmse < best_hybrid_rmse:
            best_hybrid_rmse = rmse
            best_models["Hybrid"] = {
                "model": m, "name": f"Hybrid LSTM({lstm_u})+MLP", "preds": preds,
                "metrics": {"MSE": round(mean_squared_error(y_raw, preds),4),
                            "RMSE": round(rmse,4), "MAE": round(mean_absolute_error(y_raw, preds),4)}
            }

    return best_models


# =====================================================================
#  4. PRÉDICTION ITÉRATIVE MULTI-JOURS
# =====================================================================

def predict_multistep_dl(model, model_type, last_sequence, scaler_close, n_future_days):
    predictions_scaled = []
    current_seq = last_sequence.copy()
    seq_len = current_seq.shape[0]

    for _ in range(n_future_days):
        x_input = current_seq.reshape(1, -1) if model_type == "MLP" else current_seq.reshape(1, seq_len, 1)
        next_pred = model.predict(x_input, verbose=0)[0][0]

        # Glissement : Seul le prix (les 30 premiers éléments) se décale, les features restent fixes.
        new_seq = current_seq.copy()
        new_seq[:29] = current_seq[1:30]
        new_seq[29]  = next_pred
        current_seq  = new_seq

        predictions_scaled.append(next_pred)

    return scaler_close.inverse_transform(np.array(predictions_scaled).reshape(-1, 1)).flatten()


