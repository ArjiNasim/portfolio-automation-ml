def run_tp5(companies_to_process=None):
    print("\n" + "="*60 + "\n LANCEMENT DU TP5 - DEEP LEARNING (RÉSEAUX DE NEURONES)\n" + "="*60)

    csv_files = glob.glob(os.path.join(HISTORICAL_DIR, "*.csv"))
    if not csv_files:
        print(f"❌ Aucun historique CSV trouvé dans '{HISTORICAL_DIR}'.")
        return

    if companies_to_process is None:
        companies_to_process = ["Apple", "Microsoft"] # Réduit par défaut car le DL est long

    for file_path in csv_files:
        filename = os.path.basename(file_path).replace(".csv", "")
        if filename not in companies_to_process:
            continue

        company_name = filename.replace("_history", "").replace("_", " ")
        print(f"\n🧠 Entraînement Deep Learning pour : {company_name}...")

        try:
            # 1. Données
            (X_tr_2d, X_te_2d, X_tr_3d, X_te_3d, y_tr, y_te,
             scaler_close, y_raw, input_dim) = prepare_dl_dataset(file_path)

            # 2. Entraîner Baseline ML (Random Forest) pour comparaison autonome
            rf = RandomForestRegressor(n_estimators=100, random_state=42)
            rf.fit(X_tr_2d, y_tr)
            rf_preds = scaler_close.inverse_transform(rf.predict(X_te_2d).reshape(-1, 1)).flatten()
            rf_metrics = {"MSE": round(mean_squared_error(y_raw, rf_preds),4),
                          "RMSE": round(np.sqrt(mean_squared_error(y_raw, rf_preds)),4),
                          "MAE": round(mean_absolute_error(y_raw, rf_preds),4)}

            # 3. Entraîner et optimiser Modèles DL
            dl_models = run_dl_pipeline(X_tr_2d, X_te_2d, X_tr_3d, X_te_3d, y_tr, y_te, scaler_close, y_raw, input_dim)

            # 4. Synthèse globale ML vs DL
            rows = [{"Modèle": "Baseline ML (Random Forest)", **rf_metrics}]
            for m_type, cfg in dl_models.items():
                rows.append({"Modèle": f"{cfg['name']} (DL)", **cfg["metrics"]})

            df_perf = pd.DataFrame(rows).set_index("Modèle")
            print(f" ├─ Synthèse des erreurs sur Test Set :")
            print(df_perf.sort_values(by="RMSE").to_string())

            # 5. Graphique : Confrontation Finale sur Test Set
            plt.figure(figsize=(14, 6))
            plt.plot(y_raw, color='black', linewidth=2.5, label='Valeurs réelles')
            plt.plot(rf_preds, color='grey', linestyle='-.', label='Baseline ML (Random Forest)')

            colors = {"MLP": "green", "RNN": "orange", "LSTM": "blue", "Hybrid": "purple"}
            for m_type, cfg in dl_models.items():
                plt.plot(cfg["preds"], color=colors[m_type], linestyle='--', label=cfg["name"])

            plt.title(f"Confrontation Finale ML vs DL — {company_name}")
            plt.xlabel("Jours") ; plt.ylabel("Prix ($)")
            plt.legend() ; plt.grid(True, alpha=0.3)
            plt.tight_layout()
            plt.savefig(os.path.join(PLOTS_DIR, f"test_ml_vs_dl_{company_name.replace(' ', '_')}.png"), dpi=150)
            plt.close()

            # 6. Prédiction Itérative (Futur 10j)
            print(" ├─ Génération des projections futures (10 jours)...")
            n_future = 10
            real_future = y_raw[:n_future]

            plt.figure(figsize=(12, 5))
            plt.plot(real_future, color='black', linewidth=2, label='Réalité (Futur)')

            for m_type, cfg in dl_models.items():
                last_seq = X_tr_2d[-1].copy() if m_type == "MLP" else X_tr_3d[-1].copy()
                preds = predict_multistep_dl(cfg["model"], m_type, last_seq, scaler_close, n_future)
                plt.plot(preds, color=colors[m_type], linestyle='--', marker='o', markersize=4, label=cfg["name"])

            plt.title(f"Projection Itérative DL {n_future}j — {company_name}")
            plt.legend() ; plt.grid(True, alpha=0.3)
            plt.tight_layout()
            plt.savefig(os.path.join(PLOTS_DIR, f"forecast_dl_{company_name.replace(' ', '_')}.png"), dpi=150)
            plt.close()

            print(f"✅ Terminé pour {company_name}. Graphiques sauvegardés dans '{PLOTS_DIR}'.")

        except Exception as e:
            print(f"❌ Erreur sur {company_name} : {e}")

if __name__ == "__main__":
    run_tp5()

