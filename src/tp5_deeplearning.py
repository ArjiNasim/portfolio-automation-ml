def prepare_dl_dataset(file_path, n_days=30, test_size=0.2):
    """ Prépare les données pour le Machine Learning (2D) et le Deep Learning (3D). """
    df = pd.read_csv(file_path, index_col=0)
    df.index = pd.to_datetime(df.index)
    df = df.sort_index()[['Close']].copy()

    # Features stationnaires
    sma_20      = SMAIndicator(df['Close'], window=20).sma_indicator()
    ema_20      = EMAIndicator(df['Close'], window=20).ema_indicator()
    macd_obj    = MACD(df['Close'])
    macd_raw    = macd_obj.macd()
    macd_signal = macd_obj.macd_signal()
    bb          = BollingerBands(df['Close'])
    bb_high     = bb.bollinger_hband()
    bb_low      = bb.bollinger_lband()
    bb_range    = bb_high - bb_low

    df['RSI_14']                 = RSIIndicator(df['Close'], window=14).rsi()
    df['ROC_10']                 = ROCIndicator(df['Close'], window=10).roc()
    df['Volatility_20']          = df['Close'].pct_change().rolling(20).std()
    df['price_vs_sma']           = df['Close'] / sma_20
    df['price_vs_ema']           = df['Close'] / ema_20
    df['bollinger_pct']          = np.where(bb_range != 0, (df['Close'] - bb_low) / bb_range, 0.5)
    df['macd_normalized']        = macd_raw    / df['Close']
    df['macd_signal_normalized'] = macd_signal / df['Close']
    df['month']                  = df.index.month
    df = df.dropna()

    feature_cols = [c for c in df.columns if c != 'Close']
    n_features   = len(feature_cols)

    split_idx = int(len(df) * (1 - test_size))
    train_df, test_df = df.iloc[:split_idx], df.iloc[split_idx:]

    scaler_close    = MinMaxScaler()
    scaler_features = MinMaxScaler()

    train_close_s    = scaler_close.fit_transform(train_df[['Close']])
    train_features_s = scaler_features.fit_transform(train_df[feature_cols])
    test_close_s     = scaler_close.transform(test_df[['Close']])
    test_features_s  = scaler_features.transform(test_df[feature_cols])

    def make_sequences(close_s, features_s, n):
        X2d, X3d, Y = [], [], []
        for i in range(n, len(close_s)):
            window   = close_s[i-n:i].flatten()      # (30,)
            feats    = features_s[i]                 # (n_features,)
            combined = np.concatenate([window, feats])
            X2d.append(combined)
            X3d.append(combined.reshape(-1, 1))      # (30+n_features, 1) pour RNN/LSTM
            Y.append(close_s[i, 0])
        return np.array(X2d), np.array(X3d), np.array(Y)

    X_tr_2d, X_tr_3d, y_tr = make_sequences(train_close_s, train_features_s, n_days)
    X_te_2d, X_te_3d, y_te = make_sequences(test_close_s,  test_features_s,  n_days)

    y_test_raw = scaler_close.inverse_transform(y_te.reshape(-1, 1)).flatten()
    input_dim  = n_days + n_features

    return X_tr_2d, X_te_2d, X_tr_3d, X_te_3d, y_tr, y_te, scaler_close, y_test_raw, input_dim


