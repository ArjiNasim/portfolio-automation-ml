def train_and_evaluate(model, param_grid, X_train, X_test, y_train, y_test, model_name):
    """ Gère le GridSearch, l'évaluation et la génération des SHAP values. """
    print(f"\n{'='*50}\n Entraînement : {model_name}\n{'='*50}")

    grid_search = GridSearchCV(estimator=model, param_grid=param_grid, cv=3, scoring='accuracy', n_jobs=-1)
    grid_search.fit(X_train, y_train)
    best_model = grid_search.best_estimator_

    print(f"Meilleurs paramètres : {grid_search.best_params_}")

    y_pred = best_model.predict(X_test)
    report_dict = classification_report(y_test, y_pred, output_dict=True, zero_division=0)
    print(classification_report(y_test, y_pred, target_names=['Sell (0)', 'Hold (1)', 'Buy (2)'], zero_division=0))

    # SHAP (uniquement pour modèles basés sur les arbres pour des raisons de performance)
    if model_name in ["Random Forest", "XGBoost", "LightGBM"]:
        print(f"Génération SHAP pour {model_name}...")
        try:
            explainer = shap.TreeExplainer(best_model)
            shap_values = explainer.shap_values(X_test)

            # Gestion des différences de format SHAP selon les modèles
            shap_sell = shap_values[0] if isinstance(shap_values, list) else shap_values[:, :, 0]
            shap_buy  = shap_values[2] if isinstance(shap_values, list) else shap_values[:, :, 2]

            plt.figure(figsize=(10, 6))
            shap.summary_plot(shap_sell, X_test, feature_names=X_test.columns, show=False)
            plt.title(f"SHAP - Prédiction 'Sell' ({model_name})")
            plt.tight_layout()
            plt.savefig(os.path.join(PLOTS_DIR, f"shap_sell_{model_name.replace(' ','_')}.png"))
            plt.close()

            plt.figure(figsize=(10, 6))
            shap.summary_plot(shap_buy, X_test, feature_names=X_test.columns, show=False)
            plt.title(f"SHAP - Prédiction 'Buy' ({model_name})")
            plt.tight_layout()
            plt.savefig(os.path.join(PLOTS_DIR, f"shap_buy_{model_name.replace(' ','_')}.png"))
            plt.close()
            print("Graphiques SHAP sauvegardés.")
        except Exception as e:
            print(f"⚠️ SHAP échoué pour {model_name} : {e}")

    return best_model, report_dict


# =====================================================================
#  3. DÉFINITION DES MODÈLES (AVEC GESTION DU DÉSÉQUILIBRE)
# =====================================================================

def run_all_models(X_train, X_test, y_train, y_test):
    reports = {}
    best_models = {}

    # Outil SMOTE pour les modèles ne gérant pas 'class_weight'
    smote = SMOTE(random_state=42)
    X_train_res, y_train_res = smote.fit_resample(X_train, y_train)

    # 1. Random Forest (gère class_weight)
    m_rf, r_rf = train_and_evaluate(
        RandomForestClassifier(random_state=42, class_weight='balanced'),
        {'n_estimators': [50, 100], 'max_depth': [10, 15]},
        X_train, X_test, y_train, y_test, "Random Forest"
    )
    reports["Random Forest"], best_models["Random Forest"] = r_rf, m_rf

    # 2. XGBoost (nécessite SMOTE)
    m_xgb, r_xgb = train_and_evaluate(
        XGBClassifier(random_state=42, eval_metric='mlogloss'),
        {'n_estimators': [50, 100], 'learning_rate': [0.1], 'max_depth': [5, 7]},
        X_train_res, X_test, y_train_res, y_test, "XGBoost"
    )
    reports["XGBoost"], best_models["XGBoost"] = r_xgb, m_xgb

    # 3. LightGBM (gère class_weight)
    m_lgb, r_lgb = train_and_evaluate(
        LGBMClassifier(class_weight='balanced', random_state=42, n_jobs=-1, verbose=-1),
        {'n_estimators': [50, 100], 'learning_rate': [0.05, 0.1], 'max_depth': [5, 7]},
        X_train, X_test, y_train, y_test, "LightGBM"
    )
    reports["LightGBM"], best_models["LightGBM"] = r_lgb, m_lgb

    # 4. Régression Logistique (gère class_weight)
    m_log, r_log = train_and_evaluate(
        LogisticRegression(random_state=42, class_weight='balanced'),
        {'C': [0.1, 1.0], 'solver': ['lbfgs'], 'max_iter': [1000]},
        X_train, X_test, y_train, y_test, "Logistic Regression"
    )
    reports["Logistic Regression"] = r_log

    return reports, best_models


