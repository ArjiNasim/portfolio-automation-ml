def preprocess_single_company(file_path):
    """
    Calcule les indicateurs techniques et génère les labels (Buy/Hold/Sell).
    Génère des features 100% stationnaires (ratios).
    """
    df = pd.read_csv(file_path, index_col=0)
    df.index = pd.to_datetime(df.index)
    company_returns = df[['Close']].copy()

    # Logique d'horizon et labels (J+20)
    company_returns['Close_Horizon'] = company_returns['Close'].shift(-20)
    company_returns['horizon_return'] = (company_returns['Close_Horizon'] - company_returns['Close']) / company_returns['Close']

    conditions = [
        (company_returns['horizon_return'] > 0.05),
        (company_returns['horizon_return'] < -0.05)
    ]
    # 2: Buy, 0: Sell, 1: Hold
    company_returns['label'] = np.select(conditions, [2, 0], default=1)

    # Indicateurs bruts
    sma_20 = SMAIndicator(close=company_returns['Close'], window=20).sma_indicator()
    ema_20 = EMAIndicator(close=company_returns['Close'], window=20).ema_indicator()
    macd_obj = MACD(close=company_returns['Close'])
    bb = BollingerBands(close=company_returns['Close'])

    # Features stationnaires (Ratios, Oscillateurs)
    company_returns['RSI_14'] = RSIIndicator(close=company_returns['Close'], window=14).rsi()
    company_returns['ROC_10'] = ROCIndicator(close=company_returns['Close'], window=10).roc()
    company_returns['Volatility_20'] = company_returns['Close'].pct_change().rolling(window=20).std()

    company_returns['price_vs_sma'] = company_returns['Close'] / sma_20
    company_returns['price_vs_ema'] = company_returns['Close'] / ema_20
    company_returns['bollinger_pct'] = (company_returns['Close'] - bb.bollinger_lband()) / (bb.bollinger_hband() - bb.bollinger_lband())
    company_returns['macd_norm'] = macd_obj.macd() / company_returns['Close']
    company_returns['macd_sig_norm'] = macd_obj.macd_signal() / company_returns['Close']
    company_returns['month'] = company_returns.index.month

    return company_returns.dropna()


def build_global_pipeline(folder_path=HISTORICAL_DIR):
    """ Compile toutes les entreprises, nettoie les prix absolus et standardise. """
    files = glob.glob(os.path.join(folder_path, "*.csv"))
    all_dfs = []

    for f in files:
        try:
            all_dfs.append(preprocess_single_company(f))
        except Exception as e:
            print(f"Erreur sur {f}: {e}")

    if not all_dfs:
        raise ValueError(f"Aucun DataFrame chargé depuis {folder_path}.")

    df_global = pd.concat(all_dfs, axis=0)
    print(f"[Pipeline] Dataset combiné : {df_global.shape[0]} lignes, {df_global.shape[1]} colonnes.")

    Y = df_global['label']

    # Nettoyage strict : suppression des prix absolus et variables de calcul
    cols_to_drop = ['label', 'Close', 'Close_Horizon', 'horizon_return', 'Weekly return', 'Next Day Close']
    X = df_global.drop(columns=[c for c in cols_to_drop if c in df_global.columns])

    # Standardisation
    X_scaled = pd.DataFrame(StandardScaler().fit_transform(X), columns=X.columns)

    X_train, X_test, y_train, y_test = train_test_split(
        X_scaled, Y, test_size=0.2, random_state=42, stratify=Y
    )

    print(f"[Pipeline] Distribution Train :\n{y_train.value_counts().sort_index().to_dict()}")
    return X_train, X_test, y_train, y_test


