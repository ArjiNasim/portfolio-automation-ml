def generate_summary_table(reports_dict):
    """ Extrait les métriques clés pour comparaison """
    rows = []
    for model_name, report in reports_dict.items():
        key_sell = next((k for k in report.keys() if '0' in str(k)), None)
        key_hold = next((k for k in report.keys() if '1' in str(k)), None)
        key_buy  = next((k for k in report.keys() if '2' in str(k)), None)

        rows.append({
            "Modèle": model_name,
            "Accuracy": round(report.get("accuracy", 0), 2),
            "Prec_Buy": round(report[key_buy]["precision"], 2) if key_buy else 0,
            "Rec_Buy": round(report[key_buy]["recall"], 2) if key_buy else 0,
            "Prec_Sell": round(report[key_sell]["precision"], 2) if key_sell else 0,
            "Rec_Sell": round(report[key_sell]["recall"], 2) if key_sell else 0,
            "F1_Hold": round(report[key_hold]["f1-score"], 2) if key_hold else 0,
        })

    df_res = pd.DataFrame(rows).sort_values(by="Accuracy", ascending=False)
    return df_res


# =====================================================================
#  POINT D'ENTRÉE PRINCIPAL
# =====================================================================

def run_tp3():
    print("\n" + "="*60 + "\n LANCEMENT DU TP3 - CLASSIFICATION\n" + "="*60)

    # 1. Pipeline de données
    X_train, X_test, y_train, y_test = build_global_pipeline()

    # 2. Entraînement et évaluation
    reports, models = run_all_models(X_train, X_test, y_train, y_test)

    # 3. Tableau de synthèse
    df_final = generate_summary_table(reports)
    print("\n" + "="*50 + "\n TABLEAU COMPARATIF FINAL\n" + "="*50)
    print(df_final.to_string(index=False))
    df_final.to_csv(os.path.join(PLOTS_DIR, "model_comparison.csv"), index=False)

    # 4. Feature Importances du meilleur modèle (Random Forest)
    if "Random Forest" in models:
        print("\n--- Top 10 Features (Random Forest) ---")
        importances = pd.Series(models["Random Forest"].feature_importances_, index=X_train.columns)
        print(importances.sort_values(ascending=False).head(10))

    print(f"\n✅ TP3 terminé. Les graphiques SHAP et rapports sont dans '{PLOTS_DIR}/'.")

    return models, df_final

if __name__ == "__main__":
    run_tp3()
